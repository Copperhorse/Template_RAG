"""
evaluator.py: the first quality gate. Decides which chunks are worth enriching, indexing and citing.

Rejected chunks stay in the database with their reason (so you can audit what was dropped) but are
never sent to the LLM and never indexed. Reasons are aggregated by `evaluate_chunks` so a bad
extraction (a PDF that is half table of contents) is visible at a glance.

Prose / Markdown chunks
  too short -> section heading is front/back matter (references, index, glossary, ...) -> forbidden
  prefix (figure captions) -> short citation or link -> copyright / boilerplate near the top ->
  table of contents -> source code (kept, score 85) -> low alphabetic ratio (kept only if it is a
  real data table) -> scored on length, letter ratio, sentence shape and having a heading.

Code chunks (content_type == "code", produced by chunking.code)
  empty or comment-only (licence headers) -> generated file -> imports only -> scored on size, a
  docstring and a named symbol. Heading filters do *not* apply: a function called `get_index` or
  `author` is code, not back matter.
"""

import logging
import re
from typing import Any, Dict, List, Set

logger = logging.getLogger(__name__)

_COMMENT = re.compile(r"^\s*(#|//|/\*|\*|--|\"\"\"|'''|```|~~~)")
_IMPORT_ONLY = re.compile(
    r"^\s*(import\s|from\s+\S+\s+import\s|#|__all__\b|pass\b|\)|\]|['\"\w., ]+,?\s*$|use\s|using\s|package\s|require\()"
)
_GENERATED = re.compile(r"(auto-?generated|do not edit|generated by|this file was generated)", re.I)


class ChunkEvaluator:
    def __init__(self, min_chars: int = 30):
        self.min_chars = min_chars
        self.metadata_excludes: Set[str] = {
            "table of contents", "contents", "references", "reference", "bibliography", "bibliographic",
            "further reading", "acknowledgment", "acknowledgement", "appendix", "author", "authors", "index",
            "funding", "glossary",
        }
        self._back_matter = re.compile(r"\b(?:" + "|".join(re.escape(x) for x in sorted(self.metadata_excludes, key=len, reverse=True)) + r")\b")
        self._contents_header = re.compile(r"\bcontents\b")
        self.content_prefix_excludes = ["[removed: corrupted latex content]"]
        # A caption is the only text a figure contributes to retrieval, so it is kept (and is the text half of
        # an image chunk once images are indexed).
        self.caption_prefixes = ("figure:", "figure ", "fig.", "fig ")
        # Boilerplate markers. "copyright" alone is NOT one: a README that mentions the word in a sentence is
        # content. A notice either starts a line with it (or the (c) / © sign) or says "all rights reserved".
        self.content_anywhere_excludes = ["all rights reserved", "[removed: corrupted latex content]"]
        # "(c)" alone is NOT a notice: it is the third clause of a list in a statute or a contract.
        self.copyright_line = re.compile(r"(?:^|\n)\s*(?:copyright\b|\(c\)\s*(?:19|20)\d{2}|©)", re.IGNORECASE)
        self.patterns = {
            "toc_dots": re.compile(r"\.{3,}\s*\d{1,4}(?:\s*\|)?$"),
            "url": re.compile(r"https?://|www\."),
            "doi": re.compile(r"doi:10\.\d{4,9}/"),
            "code_block": re.compile(
                r"^\s*(def\s+\w+\(|import\s+\w+|from\s+\w+\s+import\s|class\s+\w+[:(]|const\s+\w+\s*=|function\s+\w+\()",
                re.MULTILINE,
            ),
        }

    # ------------------------------------------------------------------ helpers

    @staticmethod
    def _alpha_ratio(text: str) -> float:
        if not text:
            return 0.0
        return sum(1 for c in text if c.isalpha()) / max(1, len(text))

    _FILLER = re.compile(r"[|:]|\\?_+|\.{2,}|…+|-{2,}|[\s]+")

    @classmethod
    def _content_alpha_ratio(cls, text: str) -> float:
        """Share of letters among the characters that carry content: Markdown table syntax (pipes, rules,
        padding), form blanks (____) and dot leaders are removed first. A form or table of mostly words
        scores high here and low on the raw ratio."""
        return cls._alpha_ratio(cls._FILLER.sub("", text))

    def _is_useful_table(self, text: str, metadata: Dict[str, Any]) -> bool:
        lines = text.split("\n")
        table_rows = sum(1 for line in lines if "|" in line)
        header = (metadata.get("section_header") or "").lower()
        if self._contents_header.search(header):
            return False
        return table_rows > 5 and len(lines) > 0 and (table_rows / len(lines)) > 0.4

    _PAGE_TAIL = re.compile(r"\s(\d{1,4}|[ivxlc]{1,6})$", re.I)

    def _is_table_of_contents(self, text: str, header: str = "") -> bool:
        stripped = [line.strip().rstrip("|").strip() for line in text.splitlines() if line.strip()]
        dotted = sum(1 for line in stripped if self.patterns["toc_dots"].search(line))
        if dotted > 3 or "table of contents" in text.lower()[:400]:
            return True
        # a contents table with a "Pages" column: the heading (or first row) names pages and most rows end in one
        rows = [r for r in stripped if not re.fullmatch(r"[|\s:-]+", r)]
        names_pages = re.search(r"\bpages?\b", header or "") or re.search(r"\bpages?\b", " ".join(rows[:2]).lower())
        tail = sum(1 for r in rows if self._PAGE_TAIL.search(r))
        if names_pages and len(rows) >= 4 and tail / len(rows) >= 0.6:
            return True
        return self._rises_like_contents(rows)

    _CONTENTS_FIRST = re.compile(r"(\d{1,3})[A-Z]{0,3}\.?(?:\s+\S|$)")  # "12.", "12A", "12. Title"

    @staticmethod
    def _mostly_nondecreasing(xs) -> bool:
        return sum(1 for a, b in zip(xs, xs[1:]) if b >= a) >= 0.9 * (len(xs) - 1)

    @classmethod
    def _rises_like_contents(cls, rows: List[str]) -> bool:
        """Entries numbered 1., 1A., 2. ... whose last number never decreases are a contents list (the last
        number is a page). A data table with a serial-number column does not have a non-decreasing last column."""
        pairs = []  # (entry number, trailing page number)
        for r in rows:
            cells = [c.strip() for c in r.strip("|").split("|") if c.strip()] or [r]
            first, last = cls._CONTENTS_FIRST.match(cells[0]), re.search(r"(?:^|\s)(\d{1,4})$", cells[-1])
            if first and last and sum(1 for ch in r if ch.isalpha()) >= 12:  # a contents entry has a title, not just numbers
                pairs.append((int(first.group(1)), int(last.group(1))))
        if len(pairs) < max(4, 0.7 * len(rows)):
            return False
        firsts, lasts = zip(*pairs)
        return len(set(lasts)) >= 2 and cls._mostly_nondecreasing(lasts) and cls._mostly_nondecreasing(firsts)

    @staticmethod
    def _result(should_use: bool, reason: str, c_type: str, score: float) -> Dict[str, Any]:
        if not should_use:
            logger.debug(f"Excluded: {reason}")
        return {"should_use": should_use, "reason": reason, "content_type": c_type, "quality_score": score}

    # ------------------------------------------------------------------ code

    def _evaluate_code(self, text: str, metadata: Dict[str, Any]) -> Dict[str, Any]:
        lines = [ln for ln in text.splitlines() if ln.strip()]
        real = [ln for ln in lines if not _COMMENT.match(ln)]
        if not real:
            return self._result(False, "Comment-only code (licence or banner)", "metadata", 0)
        if _GENERATED.search(text[:400]):
            return self._result(False, "Generated code", "metadata", 0)
        if all(_IMPORT_ONLY.match(ln) for ln in lines) and not metadata.get("docstring"):
            return self._result(False, "Imports only", "metadata", 10)
        if sum(len(ln.strip()) for ln in real) < 12:
            return self._result(False, "Too short/Empty", "noise", 0)

        score = 55.0
        n = len(text)
        if 200 <= n <= 2500:
            score += 20
        elif 80 <= n < 200 or 2500 < n <= 4000:
            score += 8
        if metadata.get("docstring"):
            score += 15
        if metadata.get("symbol") and metadata.get("kind") in ("function", "method", "class"):
            score += 10
        return self._result(True, "OK", "code", float(min(100, score)))

    # ------------------------------------------------------------------ prose

    def evaluate_chunk(self, content: str, metadata: Dict[str, Any]) -> Dict[str, Any]:
        text = (content or "").strip()
        text_lower = text.lower()
        metadata = metadata or {}

        if not text_lower:
            return self._result(False, "Too short/Empty", "noise", 0)
        if metadata.get("content_type") == "code":  # a code chunker's output or a fenced block
            return self._evaluate_code(text, metadata)
        if len(text) < self.min_chars:
            return self._result(False, "Too short/Empty", "noise", 0)

        header_text = ""
        for key in ("section_header", "Header 3", "Header 2", "Header 1"):
            val = metadata.get(key)
            if val:
                header_text = str(val).lower()
                break

        if self._back_matter.search(header_text):  # whole words: "author" must not match "authority"
            return self._result(False, f"Header filter: {header_text}", "metadata", 0)
        if any(text_lower.startswith(ex) for ex in self.content_prefix_excludes):
            return self._result(False, "Forbidden prefix", "other", 0)
        if text_lower.startswith(self.caption_prefixes) and len(text) >= 40 and self._alpha_ratio(text) >= 0.5:
            return self._result(True, "Figure caption", "caption", 55)
        if len(text) < 150 and (self.patterns["url"].search(text_lower) or self.patterns["doi"].search(text_lower)):
            return self._result(False, "Citation/Link chunk", "metadata", 0)
        if any(ex in text_lower[:400] for ex in self.content_anywhere_excludes) or self.copyright_line.search(text[:400]):
            return self._result(False, "Metadata keyword detected", "metadata", 0)
        if self._is_table_of_contents(text, header_text):
            return self._result(False, "Detected Table of Contents", "toc", 0)

        alpha_ratio = self._alpha_ratio(text)
        if self.patterns["code_block"].search(text):
            return self._result(True, "Source code block", "code", 85)
        if alpha_ratio < 0.30:
            if self._is_useful_table(text, metadata):
                return self._result(True, "Useful data table", "table", 75)
            if self._content_alpha_ratio(text) >= 0.30 and len(text) >= 60:  # a form, or a table of words
                return self._result(True, "Form or table of words", "table" if "|" in text else "main_content", 60)
            return self._result(False, f"Low alpha ({alpha_ratio:.2%})", "metadata", 20)

        return self._result(True, "OK", "main_content", self._quality_score(text, metadata, alpha_ratio))

    @staticmethod
    def _quality_score(text: str, metadata: Dict[str, Any], alpha_ratio: float) -> float:
        score = 50
        n = len(text)
        if 400 <= n <= 1200:
            score += 25
        elif 200 <= n < 400 or 1200 < n <= 2000:
            score += 10
        if alpha_ratio > 0.75:
            score += 15
        if text[0].isupper() and text.strip().endswith((".", "!", "?")):
            score += 10
        if len(str(metadata.get("section_header") or "")) > 3:
            score += 5
        return float(min(100, score))

    # ------------------------------------------------------------------ batches

    def evaluate_chunks(self, chunks: List[Dict[str, Any]]) -> Dict[str, Any]:
        """Attach an `evaluation` dict to a copy of every chunk and summarise the batch."""
        evaluated, scores, reasons = [], [], {}
        for chunk in chunks:
            res = self.evaluate_chunk(chunk.get("content", ""), chunk.get("metadata", {}))
            new = chunk.copy()
            new["evaluation"] = res
            evaluated.append(new)
            if res["should_use"]:
                scores.append(res["quality_score"])
            else:
                reasons[res["reason"]] = reasons.get(res["reason"], 0) + 1
        total, accepted = len(chunks), len(scores)
        return {
            "total_chunks": total,
            "accepted_chunks": accepted,
            "rejected_chunks": total - accepted,
            "acceptance_rate": (accepted / total * 100) if total else 0,
            "rejection_reasons": reasons,
            "average_quality_score": round(sum(scores) / accepted, 2) if accepted else 0,
            "evaluated_chunks": evaluated,
        }

    def filter_chunks(self, chunks: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        return [c for c in self.evaluate_chunks(chunks)["evaluated_chunks"] if c["evaluation"]["should_use"]]
